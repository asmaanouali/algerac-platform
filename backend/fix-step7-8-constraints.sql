-- Add missing columns to gaps table if not exist
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='created_by_id') THEN
    ALTER TABLE gaps ADD COLUMN created_by_id BIGINT REFERENCES users(id);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='sent_to_ree') THEN
    ALTER TABLE gaps ADD COLUMN sent_to_ree BOOLEAN DEFAULT FALSE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='sent_to_ree_date') THEN
    ALTER TABLE gaps ADD COLUMN sent_to_ree_date TIMESTAMP;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='kept_by_ree') THEN
    ALTER TABLE gaps ADD COLUMN kept_by_ree BOOLEAN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='ree_modified_description') THEN
    ALTER TABLE gaps ADD COLUMN ree_modified_description TEXT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='ree_modified_evidence') THEN
    ALTER TABLE gaps ADD COLUMN ree_modified_evidence TEXT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='sent_to_oec') THEN
    ALTER TABLE gaps ADD COLUMN sent_to_oec BOOLEAN DEFAULT FALSE;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='sent_to_oec_date') THEN
    ALTER TABLE gaps ADD COLUMN sent_to_oec_date TIMESTAMP;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='oec_accepted') THEN
    ALTER TABLE gaps ADD COLUMN oec_accepted BOOLEAN;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='oec_refusal_reason') THEN
    ALTER TABLE gaps ADD COLUMN oec_refusal_reason TEXT;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='gaps' AND column_name='oec_response_date') THEN
    ALTER TABLE gaps ADD COLUMN oec_response_date TIMESTAMP;
  END IF;
END $$;

