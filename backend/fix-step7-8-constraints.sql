-- Add gap status constraint (or update if exists)
ALTER TABLE gaps DROP CONSTRAINT IF EXISTS gaps_status_check;

ALTER TABLE gaps ADD CONSTRAINT gaps_status_check CHECK (
  status::text = ANY(ARRAY[
    'IDENTIFIED','SENT_TO_REE','KEPT_BY_REE','DISCARDED_BY_REE','SENT_TO_OEC','OEC_ACCEPTED','OEC_REFUSED',
    'AWAITING_ACTION_PLAN','PLAN_SUBMITTED','PLAN_ACCEPTED','PLAN_REJECTED',
    'IMPLEMENTATION','EVIDENCE_PROVIDED','PENDING_VERIFICATION','RESOLVED','NEEDS_COMPLEMENTARY_EVAL'
  ])
